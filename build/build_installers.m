function build_installers(which_app, outRoot)
%BUILD_INSTALLERS Build the standalone Windows installers for the release.
%
%   build_installers()            builds both applications
%   build_installers('analyzer')  builds ABL-CDI Analyzer only
%   build_installers('patlog')    builds PatLogGUI only
%
%   Produces a MATLAB Compiler *web* installer per application: a small
%   installer that downloads the matching MATLAB Runtime during a one-time
%   installation, so end users need no MATLAB licence.
%
%   Requires MATLAB Compiler. Run from a clean session (clear classes) so a
%   cached class definition cannot be baked into the build.

    if nargin < 1 || isempty(which_app), which_app = 'both'; end

    here = fileparts(mfilename('fullpath'));
    repo = fileparts(here);
    if nargin < 2 || isempty(outRoot)
        outRoot = fullfile(here, 'output');
    end
    assets = fullfile(here, 'assets');
    if ~exist(outRoot, 'dir'); mkdir(outRoot); end

    addpath(fullfile(repo, 'ABL_CDI_Analyzer', 'src'));
    addpath(fullfile(repo, 'PatLogGUI', 'src'));
    addpath(here);

    VERSION   = '1.1.0';
    AUTHOR    = 'Goga Lanchava';
    EMAIL     = 'Gogalanchava@gmail.com';
    COMPANY   = ['Department of Biomedical Technology, Faculty of Biomedical ' ...
                 'Engineering, Czech Technical University in Prague'];

    apps = struct( ...
      'key',        {'analyzer', 'patlog'}, ...
      'entry',      {fullfile(here,'launch_ABL_CDI_Analyzer.m'), fullfile(here,'launch_PatLogGUI.m')}, ...
      'exeName',    {'ABL_CDI_Analyzer', 'PatLogGUI'}, ...
      'appName',    {'ABL-CDI Analyzer', 'PatLogGUI'}, ...
      'icon',       {fullfile(assets,'abl_icon.png'), fullfile(assets,'patlog_icon.png')}, ...
      'splash',     {fullfile(assets,'abl_splash.png'), fullfile(assets,'patlog_splash.png')}, ...
      'summary',    { ...
          'Method comparison and correction for intermittent ABL and continuous CDI blood gas data', ...
          'Import, cleaning, filtering and visualisation of ABL Flex 800 blood gas exports'}, ...
      'description', { ...
          ['Aligns intermittent ABL Flex 800 blood gas measurements with continuous ' ...
           'Terumo CDI 500 monitoring, quantifies their agreement using Bland-Altman ' ...
           'statistics, correlation and regression, and fits a correction model so the ' ...
           'continuous signal tracks the reference draws more closely.' newline newline ...
           'Seven correction methods are available - bias, OLS, proportional, Deming, ' ...
           'Linnet weighted Deming, a simplified Passing-Bablok fit, and a hybrid ' ...
           'time-series/Deming method - together with automatic model selection by ' ...
           'leave-one-out cross-validation, which reports the full candidate ranking ' ...
           'rather than silently picking a winner.' newline newline ...
           'Results, corrected time series and publication-ready SVG figures can be ' ...
           'exported. See WALKTHROUGH.md in the repository to reproduce the published ' ...
           'example analyses.'], ...
          ['Imports ABL Flex 800 PatLog exports, which can carry several hundred columns ' ...
           'spanning patient measurements, calibration cycles and instrument metadata ' ...
           'across multiple patients, catheter sites and time points.' newline newline ...
           'Detects the delimiter and decimal notation automatically, selects the ' ...
           'essential columns, and provides filtering by patient, catheter placement ' ...
           'and protocol time point, with single- and multi-parameter temporal plots, ' ...
           'multi-patient overlays, catheter-location comparisons, descriptive ' ...
           'statistics and export of cleaned or patient-filtered data to Excel.' newline newline ...
           'The Statistical Analysis module requires the Statistics and Machine ' ...
           'Learning Toolbox Runtime, which this installer includes.']});

    for k = 1:numel(apps)
        a = apps(k);
        if ~strcmp(which_app, 'both') && ~strcmp(which_app, a.key)
            continue;
        end

        fprintf('\n=== building %s ===\n', a.appName);
        buildDir = fullfile(outRoot, ['build_' a.key]);
        instDir  = fullfile(outRoot, ['installer_' a.key]);

        t0 = tic;
        res = compiler.build.standaloneWindowsApplication(a.entry, ...
            'ExecutableName',         a.exeName, ...
            'ExecutableIcon',         a.icon, ...
            'ExecutableSplashScreen', a.splash, ...
            'ExecutableVersion',      [VERSION '.0'], ...
            'OutputDir',              buildDir, ...
            'Verbose',                'off');
        fprintf('  compiled in %.0f s\n', toc(t0));

        t0 = tic;
        compiler.package.installer(res, ...
            'ApplicationName', a.appName, ...
            'AuthorName',      AUTHOR, ...
            'AuthorEmail',     EMAIL, ...
            'AuthorCompany',   COMPANY, ...
            'Summary',         a.summary, ...
            'Description',     a.description, ...
            'Version',         VERSION, ...
            'InstallerName',   [a.exeName '_Installer'], ...
            'InstallerIcon',   a.icon, ...
            'InstallerLogo',   a.icon, ...
            'InstallerSplash', a.splash, ...
            'RuntimeDelivery', 'web', ...
            'Shortcut',        fullfile(buildDir, [a.exeName '.exe']), ...
            'OutputDir',       instDir);
        fprintf('  packaged in %.0f s\n', toc(t0));

        d = dir(fullfile(instDir, '*.exe'));
        for i = 1:numel(d)
            fprintf('  -> %s  (%.2f MB)\n', d(i).name, d(i).bytes/1048576);
        end
        rp = fullfile(buildDir, 'requiredMCRProducts.txt');
        if isfile(rp)
            fprintf('  runtime products: %s\n', strtrim(fileread(rp)));
        end
    end

    if strcmp(which_app, 'both')
        packageRelease(here, outRoot);
    end
end

function packageRelease(here, outRoot)
%PACKAGERELEASE Collect the two installers into the release asset.
    zipPath = fullfile(outRoot, 'Executables.zip');
    staging = fullfile(outRoot, 'staging');
    if exist(staging, 'dir'); rmdir(staging, 's'); end
    mkdir(staging);

    copyfile(fullfile(outRoot,'installer_analyzer','ABL_CDI_Analyzer_Installer.exe'), staging);
    copyfile(fullfile(outRoot,'installer_patlog','PatLogGUI_Installer.exe'), staging);
    copyfile(fullfile(here,'INSTALL.txt'), staging);

    if isfile(zipPath); delete(zipPath); end
    zip(zipPath, '*', staging);
    rmdir(staging, 's');

    d = dir(zipPath);
    fprintf('\n=== release asset ===\n  %s  (%.2f MB)\n', d.name, d.bytes/1048576);
end
